#!/usr/bin/env bash
# Copy the rendered 2x frames into src/assets/af and write src/js/geo.js (frame sizes + anchors).
# Usage: tools/assets.sh <uiflow frames dir> <afbuild frames dir>
#   uiflow frames dir: png2x/UC2-*.png, png2x/UC5-*.png, svg/UC5-S7-*.svg, demo-anchors.json  (DEMO_CLEAN renders)
#   afbuild frames dir: png/AF-*.png (2x), anchors.json
# The UC2/UC5 anchors are regenerated from ../isms-mvp-figma (tools/anchors.mjs) when the exported
# demo-anchors.json does not carry them; set FIGMA_ASSETS to the V11 asset dir (stars.jpg, cctv/).
set -euo pipefail
cd "$(dirname "$0")/.."
U="${1:?uiflow frames dir}"; AF="${2:?afbuild frames dir}"; D=src/assets/af; B="${BUILD:-$PWD/build}"
mkdir -p "$D" "$B"
for f in UC2-S1-detect-toast UC2-S2-correlate-investigation UC2-S3-contextualise-locate-live UC2-S4-sop-hover UC2-S5-sop-approved \
         UC2-S6-escalate-hover UC2-S7-escalate-dialog UC2-S8-incident-created \
         UC5-S3-contextualise-search-per-005 UC5-S5-orchestrate-sop-record-approvals UC5-S6-govern-close-dialog UC5-S7-govern-closed-export; do
  cp "$U/png2x/$f.png" "$D/$f.png"
done
for f in AF-02a-quiet AF-06-command-centre-video-wall AF-08-patrol-on-scene; do cp "$AF/png/$f.png" "$D/$f.png"; done
# the closed state without the Export menu (the film never clicks Export): stripped from the UC5-S7 SVG and rendered at 2x
node tools/closed-frame.mjs "$U" "$D/UC5-S7-govern-closed.png"
# anchors: AF frames + exported UC anchors, with the UC2/UC5 set regenerated when missing
UC="$B/uc-anchors.json"
if ! grep -q '"UC2-S1-detect-toast"' "$U/demo-anchors.json"; then
  FIGMA_ASSETS="${FIGMA_ASSETS:?set FIGMA_ASSETS (V11 asset dir) to regenerate the UC2/UC5 anchors}"
  DEMO_CLEAN=1 node tools/anchors.mjs "${FIGMA_DIR:-../isms-mvp-figma}" "$FIGMA_ASSETS" "$UC"
else
  cp "$U/demo-anchors.json" "$UC"
fi
{ printf '// Generated by tools/assets.sh. Do not edit.\nwindow.FRAMES = '; python3 -c 'import sys,json,struct
out = {}
for f in sys.argv[1:]:
    w, h = struct.unpack(">II", open(f, "rb").read()[16:24])   # PNG IHDR; frames are rendered at 2x
    out[f.rsplit("/", 1)[1][:-4]] = [w // 2, h // 2]
print(json.dumps(out))' "$D"/*.png
  printf ';\nwindow.ANCH = '; python3 -c 'import sys,json
a = json.load(open(sys.argv[1])); a.update(json.load(open(sys.argv[2])))
a["UC5-S7-govern-closed"] = {k: v for k, v in a["UC5-S7-govern-closed-export"].items() if k != "exportMenu"}   # the menu-less closed frame
print(json.dumps(a))' "$AF/anchors.json" "$UC"
  printf ';\n'; } > src/js/geo.js
ls "$D" | wc -l
