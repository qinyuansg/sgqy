#!/usr/bin/env python3
"""Render boot-partition files from the site configuration.

    render_site.py --site site.yaml --templates files/boot --out DIR
    render_site.py --site site.yaml --get os.ota.channel_url

Outputs: site.yaml (validated copy), config-foyer.txt, and the cloud-init
NoCloud seed (user-data, meta-data, network-config).
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any

import yaml

SECRET_REF = re.compile(r"^(cred|file|env):.+")
SECRET_FIELDS = (("vms", "api_key"), ("vms", "webhook", "secret"), ("monitoring", "heartbeat_token"), ("queue", "key"))
HOSTNAME = re.compile(r"^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$")


def get(data: dict[str, Any], dotted: str, default: Any = None) -> Any:
    node: Any = data
    for part in dotted.split("."):
        if not isinstance(node, dict) or part not in node:
            return default
        node = node[part]
    return node


def validate(site: dict[str, Any]) -> list[str]:
    errors = []
    for path in SECRET_FIELDS:
        value = get(site, ".".join(path))
        if value and not SECRET_REF.match(str(value)):
            errors.append(f"{'.'.join(path)} must reference a secret (cred:/file:/env:), not contain one")
    hostname = get(site, "os.hostname", "foyer-vk1")
    if not HOSTNAME.match(hostname):
        errors.append(f"os.hostname {hostname!r} is not a valid host name")
    for key in get(site, "os.ssh.authorized_keys", []) or []:
        if not str(key).startswith(("ssh-ed25519 ", "ecdsa-sha2-", "sk-ssh-ed25519@", "ssh-rsa ")):
            errors.append("os.ssh.authorized_keys must contain public keys")
    return errors


def user_data(site: dict[str, Any]) -> str:
    config: dict[str, Any] = {
        "hostname": get(site, "os.hostname", "foyer-vk1"),
        "preserve_hostname": False,
        "timezone": get(site, "os.timezone", "Etc/UTC"),
        "locale": get(site, "os.locale", "en_GB.UTF-8"),
        # Provisioning lays out the eMMC (root + encrypted data partition).
        "growpart": {"mode": "off"},
        "resize_rootfs": False,
        "ssh_pwauth": False,
        "disable_root": True,
        "users": [],
        # No interactive first-user wizard on a kiosk.
        "bootcmd": [["sh", "-c", "systemctl disable --now userconfig.service 2>/dev/null || true"]],
    }
    header = (
        "#cloud-config\n"
        "# Foyer VK-1 - generated by os-image/scripts/render_site.py.\n"
        "# Basic system identity only; the kiosk itself is provisioned by\n"
        "# foyer-provision.service from the root file system (see README).\n"
    )
    return header + yaml.safe_dump(config, sort_keys=False)


def meta_data(site: dict[str, Any]) -> str:
    device = re.sub(r"[^a-zA-Z0-9-]", "-", str(get(site, "device.id", "foyer")))
    return yaml.safe_dump({"dsmode": "local", "instance_id": f"foyer-{device}"}, sort_keys=False)


def network_config() -> str:
    # Ethernet (PoE) by DHCP. Wi-Fi, if configured, is set up by provisioning
    # from sealed secrets so no passphrase is stored on the boot partition.
    config = {"network": {"version": 2, "ethernets": {"eth0": {"dhcp4": True, "dhcp6": True, "optional": True}}}}
    return yaml.safe_dump(config, sort_keys=False)


def config_fragment(site: dict[str, Any], template: str) -> str:
    radios = []
    if get(site, "os.radios.disable_wifi", False):
        radios.append("dtoverlay=disable-wifi-pi5")
    if get(site, "os.radios.disable_bluetooth", True):
        radios.append("dtoverlay=disable-bt-pi5")
    block = "# Unused radios\n" + "\n".join(radios) if radios else "# Radios: Wi-Fi and Bluetooth enabled"
    return template.replace("@RADIOS@", block)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--site", required=True, type=Path)
    parser.add_argument("--templates", type=Path)
    parser.add_argument("--out", type=Path)
    parser.add_argument("--get")
    args = parser.parse_args()

    site = yaml.safe_load(args.site.read_text(encoding="utf-8")) or {}
    if args.get:
        value = get(site, args.get, "")
        print("" if value is None else value)
        return 0
    errors = validate(site)
    if errors:
        print("site config invalid:\n  " + "\n  ".join(errors), file=sys.stderr)
        return 1
    if not (args.out and args.templates):
        parser.error("--out and --templates are required to render")
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "site.yaml").write_text(args.site.read_text(encoding="utf-8"), encoding="utf-8")
    (args.out / "user-data").write_text(user_data(site), encoding="utf-8")
    (args.out / "meta-data").write_text(meta_data(site), encoding="utf-8")
    (args.out / "network-config").write_text(network_config(), encoding="utf-8")
    template = (args.templates / "config-foyer.txt").read_text(encoding="utf-8")
    (args.out / "config-foyer.txt").write_text(config_fragment(site, template), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
