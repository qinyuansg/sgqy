#!/usr/bin/env bash
# Copy the deck's art into src/assets: V11 frames (2x PNG), rendered visuals, backgrounds, portraits.
# Usage: tools/assets.sh <deck assets dir>   (the output folder of ../cag-pitch-deck/make_assets.mjs + make_visuals.mjs)
set -euo pipefail
cd "$(dirname "$0")/.."
A="${1:?deck assets dir}"; D=src/assets
mkdir -p "$D/v11"
cp "$A"/v11/V11-*.png "$D/v11/"
for f in viz_twin.png viz_alarms.png viz_flow.png viz_stack.png viz_trust.png viz_timeline.png viz_cover.png \
         bg3_cover.jpg bg3_section.jpg bg2_content.jpg bg2_problem.jpg bg2_close.jpg bg_cover.jpg bg_close.jpg bg_problem.jpg \
         persona_nurul.jpg persona_arjun.jpg persona_daniel.jpg persona_grace.jpg; do cp "$A/$f" "$D/"; done
# geometry for native overlays
{ printf '// Generated by tools/assets.sh. Do not edit.\nwindow.GEO = '; cat "$A/visuals.json"; printf ';\nwindow.ANCH = '; cat "$A/anchors.json"
  printf ';\nwindow.ROBOTO = '; cat ../isms-mvp-figma/lib/roboto-widths.json; printf ';\n'; } > src/js/geo.js
ls "$D" | wc -l
