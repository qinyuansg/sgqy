#!/usr/bin/env bash
# Copy the rendered 2x AV frames into src/assets/af and write src/js/geo.js (frame sizes + AV anchors).
# Usage: tools/assets.sh <frames dir>
#   frames dir: png2x/AV-*.png and demo-anchors.json (DEMO_CLEAN renders from ../isms-mvp-figma, module av-autoview.mjs;
#   the V11-faithful set: 19 frames, AV-S1 … AV-S15 and AV-A1/A1b/A2; the Incident Management frames are 1600 px wide)
set -euo pipefail
cd "$(dirname "$0")/.."
U="${1:?frames dir (png2x/AV-*.png + demo-anchors.json)}"; D=src/assets/af
mkdir -p "$D"
n=0
# copy only what changed, and replace geo.js atomically: two cuts may build at the same time.
# geo.js lists only the frames in <frames dir> (older AV renders left in src/assets/af are ignored);
# the AF-* illustration crops of the story/highlight cuts are not touched here.
for f in "$U"/png2x/AV-*.png; do cmp -s "$f" "$D/$(basename "$f")" || cp "$f" "$D/$(basename "$f")"; n=$((n + 1)); done
[ "$n" -ge 17 ] || { echo "expected at least 17 AV frames in $U/png2x, found $n" >&2; exit 1; }
G=$(mktemp src/js/.geo.XXXXXX)
{ printf '// Generated by tools/assets.sh. Do not edit.\nwindow.FRAMES = '; python3 -c 'import sys,json,struct
out = {}
for f in sys.argv[1:]:
    w, h = struct.unpack(">II", open(f, "rb").read()[16:24])   # PNG IHDR; frames are rendered at 2x
    out[f.rsplit("/", 1)[1][:-4]] = [w // 2, h // 2]
print(json.dumps(out))' $(for f in "$U"/png2x/AV-*.png; do printf '%s ' "$D/$(basename "$f")"; done)
  printf ';\nwindow.ANCH = '; python3 -c 'import sys,json
a = json.load(open(sys.argv[1]))
print(json.dumps({k: v for k, v in a.items() if k.startswith("AV-")}))' "$U/demo-anchors.json"
  printf ';\n'; } > "$G"
if cmp -s "$G" src/js/geo.js; then rm -f "$G"; else chmod 644 "$G"; mv -f "$G" src/js/geo.js; fi
echo "$n AV frames → $D, geo.js written"
