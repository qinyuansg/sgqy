#!/usr/bin/env bash
# Build the film's art into src/assets: the AgilFence V11 frames at 2x (no baked pointer, plus the
# in-between states), the fence camera scenes, and the back-view persona photos from the deck.
# Usage: tools/assets.sh <V11 assets dir> <deck assets dir>
#   V11 assets dir: logo_s.png, stars.jpg, cctv/*.jpg + meta.json (incl. `node render-cctv.mjs <dir>/cctv fence_`)
#   deck assets dir: output of ../cag-pitch-deck/make_assets.mjs (persona_*.jpg)
set -euo pipefail
cd "$(dirname "$0")/.."
A="${1:?V11 assets dir}"; DK="${2:?deck assets dir}"; D=src/assets; B="${BUILD:-$PWD/build}"
mkdir -p "$D/af" "$D/cctv"
AF_FILM=1 node ../isms-mvp-figma/build-agilfence.mjs "$B/frames" "$A" > /dev/null
cp "$B"/frames/png/AF-*.png "$D/af/"
for f in fence_ptz fence_pre fence_wide fence_inside fence_patrol thermal; do cp "$A/cctv/${f}.jpg" "$A/cctv/${f}_clean.jpg" "$D/cctv/"; done
cp "$A/cctv/lidar_clean.jpg" "$A/logo_s.png" "$D/cctv/" && mv "$D/cctv/logo_s.png" "$D/logo_s.png"
for p in nurul arjun daniel; do cp "$DK/persona_$p.jpg" "$D/"; done
# geometry for native overlays: frame sizes, callout anchors, camera-scene boxes
{ printf '// Generated by tools/assets.sh. Do not edit.\nwindow.FRAMES = '; python3 -c 'import sys,json,struct
out = {}
for f in sys.argv[1:]:
    w, h = struct.unpack(">II", open(f, "rb").read()[16:24])   # PNG IHDR; frames are rendered at 2x
    out[f.rsplit("/", 1)[1][:-4]] = [w // 2, h // 2]
print(json.dumps(out))' "$D"/af/AF-*.png
  printf ';\nwindow.ANCH = '; cat "$B/frames/anchors.json"
  printf ';\nwindow.CCTV = '; cat "$A/cctv/meta.json"; printf ';\n'; } > src/js/geo.js
ls "$D" "$D/af" | wc -l
