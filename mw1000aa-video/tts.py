#!/usr/bin/env python3
"""Generate the narration for the MW1000AA explainer with Kokoro TTS.

Reads script.json, synthesises every beat (cached), lays the beats out on a
timeline with pauses, and writes:
  build/narration.wav   full voice-over track (24 kHz mono)
  timeline.js           window.TIMELINE used by scenes.html for sync + captions
Usage: python tts.py <kokoro_model_dir>
"""
import hashlib, json, os, re, sys
import numpy as np
import soundfile as sf

HERE = os.path.dirname(os.path.abspath(__file__))
MODEL_DIR = sys.argv[1]
BUILD = os.path.join(HERE, "build")
CACHE = os.path.join(BUILD, "tts_cache")
os.makedirs(CACHE, exist_ok=True)

SR = 24000
LEAD_IN = 0.9      # silence before the first beat of a chapter
GAP = 0.45         # pause between beats
TAIL = 1.1         # hold after the last beat of a chapter
INTRO_PAD = 0.6

AUTO = [  # caption text -> speakable text (applied when a beat has no "say")
    (r"NUCTECH™ ", "Nuctech "), (r"NUCTECH", "Nuctech"),
    (r"\bMW1000AA\b", "M W one thousand A-A"), (r"\bECAC\b", "ee-cack"),
    (r"\bATR\b", "A-T-R"), (r"\bIEDs\b", "I-E-Ds"), (r"\bLED\b", "L-E-D"),
    (r"\bRF\b", "R-F"), (r"R&D", "R and D"), (r"\bAI\b", "A-I"),
    (r"\bCE\b", "C-E"), (r"\b3D\b", "three-D"), (r"&", "and"),
]

def speakable(b):
    if b.get("say"):
        return b["say"]
    s = b["cap"]
    for pat, rep in AUTO:
        s = re.sub(pat, rep, s)
    return s

def trim(x, thr=0.006):
    idx = np.where(np.abs(x) > thr)[0]
    if len(idx) == 0:
        return x
    a = max(0, idx[0] - int(0.03 * SR)); b = min(len(x), idx[-1] + int(0.08 * SR))
    return x[a:b]

def chunk_caption(text, maxlen=118):
    """Split a caption into on-screen chunks (sentences, then clauses)."""
    sents = re.split(r"(?<=[.?!:])\s+(?=[A-Z0-9“\"'(])", text.strip())
    out = []
    for s in sents:
        while len(s) > maxlen:
            mid = len(s) // 2
            cands = [m.end() for m in re.finditer(r"[,;—]\s", s)]
            if not cands:
                cands = [m.end() for m in re.finditer(r"\s", s)]
            cut = min(cands, key=lambda c: abs(c - mid))
            out.append(s[:cut].strip()); s = s[cut:].strip()
        if s:
            out.append(s)
    # merge very short fragments into the previous chunk
    merged = []
    for c in out:
        if merged and len(c) < 28 and len(merged[-1]) + len(c) < maxlen + 10:
            merged[-1] += " " + c
        else:
            merged.append(c)
    return merged

def main():
    script = json.load(open(os.path.join(HERE, "script.json")))
    voice, speed = script["voice"], script["speed"]
    kokoro = None
    t = INTRO_PAD
    timeline = {"chapters": []}
    pieces = []
    for ch in script["chapters"]:
        cstart = t
        t += LEAD_IN
        beats = []
        for i, b in enumerate(ch["beats"]):
            text = speakable(b)
            key = hashlib.sha1(f"{voice}|{speed}|{text}".encode()).hexdigest()[:16]
            path = os.path.join(CACHE, key + ".wav")
            if not os.path.exists(path):
                if kokoro is None:
                    from kokoro_onnx import Kokoro
                    kokoro = Kokoro(os.path.join(MODEL_DIR, "kokoro-v1.0.onnx"),
                                    os.path.join(MODEL_DIR, "voices-v1.0.bin"))
                audio, sr = kokoro.create(text, voice=voice, speed=speed, lang="en-us")
                assert sr == SR
                sf.write(path, trim(np.asarray(audio, dtype=np.float32)), SR)
                print(f"  synth {ch['id']}#{i} ({len(audio)/SR:.1f}s)", flush=True)
            audio, _ = sf.read(path, dtype="float32")
            dur = len(audio) / SR
            chunks = chunk_caption(b["cap"])
            total_chars = sum(len(c) for c in chunks)
            ct, cl = t, []
            for c in chunks:
                cd = dur * len(c) / total_chars
                cl.append({"t0": round(ct, 3), "t1": round(ct + cd, 3), "text": c})
                ct += cd
            beats.append({"start": round(t, 3), "dur": round(dur, 3), "cap": b["cap"], "chunks": cl})
            pieces.append((t, audio))
            t += dur + (GAP if i < len(ch["beats"]) - 1 else 0)
        t += TAIL
        timeline["chapters"].append({"id": ch["id"], "num": ch["num"], "title": ch["title"],
                                     "start": round(cstart, 3), "end": round(t, 3), "beats": beats})
    total = t + 5.0  # end card hold
    timeline["total"] = round(total, 3)
    track = np.zeros(int(total * SR) + SR, dtype=np.float32)
    for st, a in pieces:
        i = int(st * SR); track[i:i + len(a)] += a
    peak = np.max(np.abs(track)) or 1
    track = track / peak * 0.89
    sf.write(os.path.join(BUILD, "narration.wav"), track, SR)
    with open(os.path.join(HERE, "timeline.js"), "w") as f:
        f.write("// generated by tts.py — do not edit\nwindow.TIMELINE = ")
        json.dump(timeline, f, indent=1, ensure_ascii=False)
        f.write(";\n")
    print(f"total {total:.1f}s ({total/60:.1f} min)")

if __name__ == "__main__":
    main()
