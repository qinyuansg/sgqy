#!/usr/bin/env python3
"""Inline the Tabler icons used by scenes.html into icons.js (MIT, tabler.io)."""
import json, os, re, sys
src = sys.argv[1]  # .../tabler-icons/package/icons/outline
names = """user user-shield user-check users users-group presentation-analytics chart-line building-airport plane
building building-bank scale gavel shield-check shield-lock lock eye-off eye building-factory-2 cpu truck-delivery
tool tools school world train building-hospital building-stadium building-warehouse passport id military-rank
radioactive clock hourglass hand-stop hand-finger circle-check circle-x bolt volume temperature droplet ruler-measure
weight device-desktop device-tablet bulb shoe knife bomb bottle pill device-mobile wave-sine brain affiliate
cube-3d-sphere settings certificate coin trending-up refresh recycle clipboard-check map-pin calendar search plug
antenna broadcast database code shirt accessible heartbeat file-certificate receipt ticket door-enter door-exit walk
box basket alert-triangle x check arrow-right arrow-left target focus-2 scan radar-2 chart-bar cash report-analytics
building-community chess-knight flag sparkles stethoscope wifi cloud-computing server shopping-cart package
rotate-clockwise-2 list-check speakerphone wallet key arrows-exchange lighter-not affiliate-filled growing
microscope atom-2 cell-signal-5 activity-heartbeat zoom-scan components topology-star-3 stack-2 adjustments
gauge timeline route stairs-up moneybag coins hammer flask-2 user-question question-mark users-plus subway
building-castle building-skyscraper tie mood-smile layout-dashboard hierarchy-3 badge award ear-off fingerprint""".split()
icons, missing = {}, []
for n in names:
    p = os.path.join(src, n + ".svg")
    if not os.path.exists(p):
        missing.append(n); continue
    s = open(p).read()
    inner = re.search(r"<svg[^>]*>(.*)</svg>", s, re.S).group(1)
    inner = re.sub(r'<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*/>', "", inner)
    icons[n] = re.sub(r"\s+", " ", inner).strip()
open(os.path.join(os.path.dirname(__file__), "..", "icons.js"), "w").write(
    "// Tabler Icons (MIT License, https://tabler.io/icons) — generated by tools/build_icons.py\nwindow.ICONS = "
    + json.dumps(icons) + ";\n")
print(len(icons), "icons; missing:", missing)
